#!/usr/bin/env python3
"""Generate a Lean file for a fixed tree cleaving diagram (BO13a figures).

Usage: gen_tree_shape.py SPEC.json OUT.lean

SPEC fields:
  name      : namespace/inductive name, e.g. "F62"
  doc       : one-line description for the module docstring
  verts     : list of vertex names (Lean identifiers)
  objs      : list of object variable names, one per vertex
  arrows    : list of [src, tgt, morphism variable name]
  copy      : {"type": "D", "m": m, "spine": [...], "leaves": [l0, l1, l2, l3]}
  theorem   : name of the generated theorem, e.g. "not_f62"

The generated theorem takes, in order: hmin hL hR τ hτ hτ0, the morphisms,
then hypotheses
  h0_<u>_<v>   : ¬FactorsThroughMorphism τ (value of the path u ⇝ v)
  hi_<f>       : ¬IsIso f                     (each arrow f)
  hl_<f>_<f'>_<y> : ¬∃ g, f ≫ g = f' ≫ (path c' ⇝ y)   (out-arrows f, f' of x)
  hr_<f>_<f'>_<x> : ¬∃ g, g ≫ f = (path x ⇝ c') ≫ f'   (in-arrows f, f' of y)
with identity paths omitted. Path values are left-associated.
"""
import json, sys

spec = json.load(open(sys.argv[1]))
out = sys.argv[2]
N = spec['name']; V = spec['verts']; O = spec['objs']; A = spec['arrows']
obj = dict(zip(V, O))
mors = [a[2] for a in A]
outs = {v: [a for a in A if a[0] == v] for v in V}
ins = {v: [a for a in A if a[1] == v] for v in V}

# all paths (tree: unique)
paths = {}
def dfs(start, v, seq):
    paths[(start, v)] = seq
    for (s, t, f) in outs[v]:
        dfs(start, t, seq + [f])
for v in V:
    dfs(v, v, [])

def val(seq):
    if not seq:
        return None
    e = seq[0]
    for f in seq[1:]:
        e = f'({e}) ≫ {f}' if ' ' in e else f'{e} ≫ {f}'
    return e

def tval(seq):  # value as written in the table (left associated)
    v = val(seq)
    return '𝟙 _' if v is None else v

# parent function: BFS from root = first vertex
root = V[0]
par = {root: None}; ht = {root: 0}; order = [root]
adj = {v: [] for v in V}
for (s, t, f) in A:
    adj[s].append(t); adj[t].append(s)
i = 0
while i < len(order):
    v = order[i]; i += 1
    for w in adj[v]:
        if w not in par:
            par[w] = v; ht[w] = ht[v] + 1; order.append(w)
assert len(order) == len(V), 'not connected'
assert len(A) == len(V) - 1, 'not a tree'

L = []
w = L.append
w('module\n')
w('public import LargeIndecomposable.Cleaving.Shapes.ShapeD6')
if spec.get('mild', False):
    w('public import LargeIndecomposable.Cleaving.Basic.Tools')
w('')
w('/-!')
w(f'# The tree diagram `{N}`\n')
w(spec['doc'])
w('\nGenerated by `scripts/gen_tree_shape.py`.')
w('-/\n')
w('@[expose] public section\n')
w('set_option autoImplicit false\n')
w('noncomputable section\n')
w('namespace LargeIndecomposable\n')
w('open CategoryTheory Limits RayCat\n')
w('universe u\n')
w('namespace RayCat\n')
w(f'/-- Vertices of the diagram `{N}`. -/')
w(f'inductive {N}')
w('  | ' + ' | '.join(V))
w('  deriving DecidableEq\n')
w(f'namespace {N}\n')
w(f'instance : Fintype {N} := ⟨{{{", ".join(V)}}}, by intro v; cases v <;> simp⟩\n')
w('/-- The orientation. -/')
w(f'def ob : {N} → {N} → Bool')
w('  | ' + ' | '.join(f'{s}, {t}' for (s, t, f) in A) + ' => true')
w('  | _, _ => false\n')
w('/-- The orientation as a relation. -/')
w(f'abbrev o (u v : {N}) : Prop := ob u v = true\n')
w('/-- The graph. -/')
w(f'def G : SimpleGraph {N} := SimpleGraph.fromRel o\n')
w(f'lemma adj_iff (u v : {N}) : G.Adj u v ↔ o u v ∨ o v u := by')
w('  rw [G, SimpleGraph.fromRel_adj]')
w('  cases u <;> cases v <;> decide\n')
w('instance : DecidableRel G.Adj := fun u v ↦ decidable_of_iff _ (adj_iff u v).symm\n')
w(f'lemma ho (u v : {N}) (h : o u v) : G.Adj u v := (adj_iff u v).2 (Or.inl h)\n')
w(f'lemma hcov (u v : {N}) (h : G.Adj u v) : o u v ∨ o v u := (adj_iff u v).1 h\n')
w(f'lemma hasym (u v : {N}) (h : o u v) : ¬o v u := by')
w('  revert h; cases u <;> cases v <;> decide\n')
w('/-- The parent function. -/')
w(f'def par : {N} → Option {N}')
for v in V:
    w(f'  | {v} => ' + ('none' if par[v] is None else f'some {par[v]}'))
w('')
w('/-- The height. -/')
w(f'def ht : {N} → ℕ')
for v in V:
    w(f'  | {v} => {ht[v]}')
w('')
w('lemma isAcyclic : G.IsAcyclic :=')
w('  isAcyclic_of_parent G par ht (fun u v ↦ by rw [adj_iff]; cases u <;> cases v <;> decide)')
w('    (fun u v h ↦ by cases u <;> cases v <;> simp_all [par, ht])\n')

cp = spec['copy']
if cp['type'] == 'D':
    m = cp['m']; sp = cp['spine']; lv = cp['leaves']
    assert len(sp) == m + 1 and len(lv) == 4
    def ite(var, names):
        s = names[-1]
        for k in range(len(names) - 2, -1, -1):
            s = f'if ({var} : ℕ) = {k} then {names[k]} else {s}'
        return s
    w('open LargeIndecomposable.Foundations.Quiver in')
    w(f'/-- The vertex map of the copy of `D̃`. -/')
    w(f'def cmap : AffineD {m} → {N}')
    w(f'  | .spine j => {ite("j", sp)}')
    w(f'  | .leaf i => {ite("i", lv)}\n')
    w('open LargeIndecomposable.Foundations.Quiver in')
    w('/-- The copy of `D̃`. -/')
    w(f'def copy : (underlyingGraph (AffineD {m})).Copy G :=')
    w(f'  copyD G {m} cmap (by')
    w('    intro u v h')
    w("    rcases u with i | j <;> rcases v with i' | j'")
    w("    · fin_cases i <;> fin_cases i' <;> simp_all [cmap]")
    w("    · fin_cases i <;> fin_cases j' <;> simp_all [cmap]")
    w("    · fin_cases j <;> fin_cases i' <;> simp_all [cmap]")
    w("    · fin_cases j <;> fin_cases j' <;> simp_all [cmap])")
    w('    (fun i ↦ by')
    w('      fin_cases i')
    w('      · rw [AffineD.leafTarget_of_lt_two _ (by decide)]; simp [cmap]; decide')
    w('      · rw [AffineD.leafTarget_of_lt_two _ (by decide)]; simp [cmap]; decide')
    w('      · rw [AffineD.leafTarget_of_not_lt_two _ (by decide)]; simp [cmap]; decide')
    w('      · rw [AffineD.leafTarget_of_not_lt_two _ (by decide)]; simp [cmap]; decide)')
    w("    (fun j j' h ↦ by fin_cases j <;> fin_cases j' <;> simp_all [cmap] <;> decide)\n")
    hD = f'(OT.not_isRepresentationFinite_affineD ho hcov k {m} copy)'
elif cp['type'] == 'E6':
    ce = cp['center']; inn = cp['inner']; outr = cp['outer']
    assert len(inn) == 3 and len(outr) == 3
    def ite(var, names):
        s = names[-1]
        for k in range(len(names) - 2, -1, -1):
            s = f'if ({var} : ℕ) = {k} then {names[k]} else {s}'
        return s
    w('open LargeIndecomposable.Foundations.Quiver in')
    w('/-- The vertex map of the copy of `Ẽ₆`. -/')
    w(f'def cmap : AffineE6 → {N}')
    w(f'  | .center => {ce}')
    w(f'  | .inner i => {ite("i", inn)}')
    w(f'  | .outer i => {ite("i", outr)}\n')
    w('open LargeIndecomposable.Foundations.Quiver in')
    w('/-- The copy of `Ẽ₆`. -/')
    w('def copy : (underlyingGraph AffineE6).Copy G :=')
    w('  copyOf G cmap (by')
    w('    intro u v h')
    w('    rcases u with _ | i | i <;> rcases v with _ | j | j <;>')
    w('      (try fin_cases i) <;> (try fin_cases j) <;> simp_all [cmap])')
    w('    (by')
    w('      intro a b e')
    w('      rcases a with _ | i | i <;> rcases b with _ | j | j')
    w('      all_goals first')
    w('        | exact (IsEmpty.false e).elim')
    w('        | exact e.elim')
    w('        | (obtain rfl : i = j := e.down; fin_cases i <;> simp only [cmap] <;> decide)')
    w('        | (fin_cases i <;> simp only [cmap] <;> decide))\n')
    hD = '(OT.not_isRepresentationFinite_affineE6 ho hcov k copy)'
elif cp['type'] == 'E7':
    ce = cp['center']; sh = cp['short']; lg = cp['long']
    assert len(lg) == 2 and all(len(l) == 3 for l in lg)
    def ite2(names):
        return f'if (i : ℕ) = 0 then {names[0]} else {names[1]}'
    w('open LargeIndecomposable.Foundations.Quiver in')
    w('/-- The vertex map of the copy of `Ẽ₇` (long arms listed from the centre). -/')
    w(f'def cmap : AffineE7 → {N}')
    w(f'  | .center => {ce}')
    w(f'  | .short => {sh}')
    w(f'  | .inner i => {ite2([lg[0][0], lg[1][0]])}')
    w(f'  | .middle i => {ite2([lg[0][1], lg[1][1]])}')
    w(f'  | .outer i => {ite2([lg[0][2], lg[1][2]])}\n')
    w('open LargeIndecomposable.Foundations.Quiver in')
    w('/-- The copy of `Ẽ₇`. -/')
    w('def copy : (underlyingGraph AffineE7).Copy G :=')
    w('  copyOf G cmap (by')
    w('    intro u v h')
    w('    rcases u with _ | _ | i | i | i <;> rcases v with _ | _ | j | j | j <;>')
    w('      (try fin_cases i) <;> (try fin_cases j) <;> simp_all [cmap])')
    w('    (by')
    w('      intro a b e')
    w('      change AffineE7.Arrow a b at e')
    w('      cases e with')
    w('      | outerMiddle i => fin_cases i <;> simp only [cmap] <;> decide')
    w('      | middleInner i => fin_cases i <;> simp only [cmap] <;> decide')
    w('      | innerCenter i => fin_cases i <;> simp only [cmap] <;> decide')
    w('      | shortCenter => simp only [cmap]; decide)\n')
    hD = '(OT.not_isRepresentationFinite_affineE7 ho hcov k copy)'
elif cp['type'] == 'E8':
    ce = cp['center']; sh = cp['short']; md = cp['medium']; lg = cp['long']
    assert len(md) == 2 and len(lg) == 5
    w('open LargeIndecomposable.Foundations.Quiver in')
    w('/-- The vertex map of the copy of `Ẽ₈` (arms listed from the centre). -/')
    w(f'def cmap : AffineE8 → {N}')
    w(f'  | .center => {ce}')
    w(f'  | .short => {sh}')
    w(f'  | .medium4 => {md[0]}')
    w(f'  | .medium2 => {md[1]}')
    for i, v in enumerate(lg):
        w(f'  | .long{5 - i} => {v}')
    w('')
    w('open LargeIndecomposable.Foundations.Quiver in')
    w('/-- The copy of `Ẽ₈`. -/')
    w('def copy : (underlyingGraph AffineE8).Copy G :=')
    w('  copyOf G cmap (by')
    w('    intro u v h')
    w('    cases u <;> cases v <;> simp_all [cmap])')
    w('    (by')
    w('      intro a b e')
    w('      change AffineE8.Arrow a b at e')
    w('      cases e <;> simp only [cmap] <;> decide)\n')
    hD = '(OT.not_isRepresentationFinite_affineE8 ho hcov k copy)'
else:
    raise SystemExit('copy type not supported yet')

objargs = ' '.join(f'({o} := {o})' for o in O)
w('section Diagram\n')
w('variable {P : Type} [Category.{0} P] [HasZeroMorphisms P] {' + ' '.join(O) + ' : P}')
w('  ' + ' '.join(f'({f} : {obj[s]} ⟶ {obj[t]})' for (s, t, f) in A) + '\n')
w('/-- The objects. -/')
w(f'def obj : {N} → P')
w('  ' + ' '.join(f'| {v} => {obj[v]}' for v in V) + '\n')
w('/-- The arrows. -/')
w(f'def arr : ∀ u v : {N}, o u v → ((obj {objargs} u) ⟶ obj {objargs} v)')
for (s, t, f) in A:
    w(f'  | {s}, {t}, _ => {f}')
w('  | _, _, _ => 0\n')
w('/-- The path values. -/')
w(f'def tab : ∀ u v : {N}, Option ((obj {objargs} u) ⟶ obj {objargs} v)')
for (u, v), seq in paths.items():
    w(f'  | {u}, {v} => some ({tval(seq)})')
w('  | _, _ => none\n')
w('end Diagram\n')
w(f'end {N}\n')
w('end RayCat\n')
MILD = spec.get('mild', False)
if MILD:
    w('namespace RayCat\n')
    w('variable {P : Type} [Category.{0} P] [HasZeroMorphisms P] [IsRayCategory P] [Fintype P]')
    w('  [DecidableEq P] [IsFiniteRayCategory P] {k : Type u} [Field k] [Infinite k]\n')
else:
    w('namespace RayQuiver\n')
    w('namespace MulBasis\n')
    w('variable {P : Type} [Category.{0} P] [HasZeroMorphisms P] [IsRayCategory P] [Fintype P]')
    w('  [DecidableEq P] [IsFiniteRayCategory P] {k : Type u} [Field k] [Infinite k]')
    w('  {A : Type u} [Ring A] [Algebra k A] (B : MulBasis k P A)\n')

hyps = []
for (u, v), seq in paths.items():
    if seq:
        hyps.append((f'h0_{u}_{v}', f'¬FactorsThroughMorphism τ ({val(seq)})'))
for f in mors:
    hyps.append((f'hi_{f}', f'¬IsIso {f}'))
for x in V:
    for (_, c, f) in outs[x]:
        for (_, c2, f2) in outs[x]:
            if c == c2:
                continue
            for (a, y), seq in paths.items():
                if a != c2:
                    continue
                rhs = f2 if not seq else f'{f2} ≫ {val(seq) if len(seq) == 1 else "(" + val(seq) + ")"}'
                hyps.append((f'hl_{f}_{f2}_{y}', f'¬∃ g, {f} ≫ g = {rhs}'))
for y in V:
    for (c, _, f) in ins[y]:
        for (c2, _, f2) in ins[y]:
            if c == c2:
                continue
            for (x, b), seq in paths.items():
                if b != c2:
                    continue
                if not seq:
                    lhs = f2
                else:
                    pv = val(seq)
                    lhs = (pv if len(seq) == 1 else f'({pv})') + f' ≫ {f2}'
                hyps.append((f'hr_{f}_{f2}_{x}', f'¬∃ g, g ≫ {f} = {lhs}'))

w('set_option maxHeartbeats 8000000 in')
w(f'open {N} in')
if not MILD:
    w('include B in')
w(f'/-- **No cleaving diagram `{N}` in `P/τ`.** -/')
if MILD:
    w(f'theorem MildHyp.{spec["theorem"]} (hM : MildHyp k P)')
    w('    {a b : P} (τ : a ⟶ b) (hτ : ¬IsIso τ)')
else:
    w(f'theorem {spec["theorem"]}')
    w('    (hmin : ∀ I : TwoSidedIdeal A, I ≠ ⊥ → Statement.IsRepresentationFinite (A ⧸ I.asIdeal))')
    w('    (hL : LeftCancel P) (hR : RightCancel P) {a b : P} (τ : a ⟶ b) (hτ : ¬IsIso τ)')
w('    (hτ0 : τ ≠ 0) {' + ' '.join(O) + ' : P}')
w('    ' + ' '.join(f'({f} : {obj[s]} ⟶ {obj[t]})' for (s, t, f) in A))
for (n_, t_) in hyps:
    w(f'    ({n_} : {t_})')
w('    : False := by')
w('  haveI : Fact (LargeIndecomposable.Foundations.Quiver.IsAcyclic (OT G o)) := ⟨OT.isAcyclic ho hasym isAcyclic⟩')
margs = ' '.join(mors)
if MILD:
    w(f'  refine hM.not_tree_table τ hτ hτ0 G o ho hasym isAcyclic')
else:
    w(f'  refine B.not_tree_table hmin hL hR τ hτ hτ0 G o ho hasym isAcyclic')
w(f'    {hD} obj (arr {margs})')
w(f'    (tab {margs}) (fun v ↦ by cases v <;> rfl) ?_ ?_ ?_ ?_ ?_')
w('  · intro x y z h f hf')
w('    cases y <;> cases z <;> (try exact absurd h (by decide)) <;> cases x <;>')
w('      simp only [tab, reduceCtorEq, Option.some.injEq] at hf <;>')
w('      (first | subst hf | obtain rfl := Option.some.inj hf) <;>')
w('      first')
w('      | (rw [Category.id_comp]; rfl)')
w('      | rfl')
w('  · intro x y f hf hne')
w('    cases x <;> cases y <;> (try exact absurd rfl hne) <;>')
w('      simp only [tab, reduceCtorEq, Option.some.injEq] at hf <;>')
w('      (first | subst hf | obtain rfl := Option.some.inj hf) <;> assumption')
w('  · intro x y h')
w('    cases x <;> cases y <;> first')
w('      | exact absurd h (by decide)')
w('      | assumption')
w('  · intro x c c\' y h h\' f hne hf')
w('    cases x <;> cases c <;> (try exact absurd h (by decide)) <;> cases c\' <;>')
w('      (try exact absurd h\' (by decide)) <;> (try exact absurd rfl hne) <;> cases y <;>')
w('      simp only [tab, reduceCtorEq, Option.some.injEq] at hf <;>')
w('      (first | subst hf | obtain rfl := Option.some.inj hf) <;>')
w('      first')
w('      | (rw [Category.comp_id]; assumption)')
w('      | assumption')
w('  · intro x c c\' y h h\' f hne hf')
w('    cases y <;> cases c <;> (try exact absurd h (by decide)) <;> cases c\' <;>')
w('      (try exact absurd h\' (by decide)) <;> (try exact absurd rfl hne) <;> cases x <;>')
w('      simp only [tab, reduceCtorEq, Option.some.injEq] at hf <;>')
w('      (first | subst hf | obtain rfl := Option.some.inj hf) <;>')
w('      first')
w('      | (rw [Category.id_comp]; assumption)')
w('      | assumption\n')
if MILD:
    w('end RayCat\n')
else:
    w('end MulBasis\n')
    w('end RayQuiver\n')
w('end LargeIndecomposable')
open(out, 'w').write('\n'.join(L) + '\n')
print(f'{len(hyps)} hypotheses:')
for (n_, t_) in hyps:
    print(f'  {n_} : {t_}')
