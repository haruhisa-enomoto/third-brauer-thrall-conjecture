#!/usr/bin/env python3
"""Generate a Lean file for a fixed thin cleaving diagram (a finite poset with
commutative squares and zero relations), BO13a figures.

Usage: gen_thin_shape.py SPEC.json OUT.lean

With "mild": true in SPEC, the theorem is `MildHyp.<theorem>` taking
`hM : MildHyp k P` instead of `hmin hL hR` (Cleaving/Basic/Tools.lean).

SPEC fields: name, doc, theorem, verts, objs, arrows [[src, tgt, mor]],
  zero : [[x, z], ...] pairs whose morphisms vanish (optional),
  choose : {"x z": [mor, ...]} chosen path for a pair (optional; default:
           first path found).
The generated theorem takes hmin hL hR τ hτ hτ0, the morphisms, then
  hD : the thin category is representation-infinite,
  hc_i : commutativity (non-chosen path = chosen path), right-associated,
  hz_i : zero relations (path = 0), right-associated,
  h0_<x>_<y> : ¬FactorsThroughMorphism τ (value x ⇝ y),
  hlft_<x>_<z>_<y> / hrgt_<x>_<z>_<y> : failures of the arrow conditions.
"""
import json, sys, itertools

spec = json.load(open(sys.argv[1]))
out = sys.argv[2]
N = spec['name']; V = spec['verts']; O = spec['objs']; A = spec['arrows']
obj = dict(zip(V, O))
zero = set(tuple(p) for p in spec.get('zero', []))
choose = {tuple(k.split()): v for k, v in spec.get('choose', {}).items()}
outs = {v: [a for a in A if a[0] == v] for v in V}
ins = {v: [a for a in A if a[1] == v] for v in V}
arrmap = {(s, t): f for (s, t, f) in A}

# all paths
allp = {}
def dfs(start, v, seq):
    allp.setdefault((start, v), []).append(seq)
    for (s, t, f) in outs[v]:
        dfs(start, t, seq + [f])
for v in V:
    dfs(v, v, [])
reach = {p for p in allp}
le = {(x, y) for (x, y) in reach if (x, y) not in zero or x == y}
for (x, y) in zero:
    assert x != y

def chosen(x, y):
    if (x, y) in choose:
        return choose[(x, y)]
    return allp[(x, y)][0]

def lval(seq):  # left-associated
    if not seq:
        return '𝟙 _'
    e = seq[0]
    for f in seq[1:]:
        e = f'({e}) ≫ {f}' if ' ' in e else f'{e} ≫ {f}'
    return e

def rval(seq):  # right-associated
    if not seq:
        return '𝟙 _'
    e = seq[-1]
    for f in reversed(seq[:-1]):
        e = f'{f} ≫ {e}'
    return e

def par(e):
    return e if ' ' not in e else f'({e})'

# Hasse arrows: the quiver arrows
ar = {(s, t) for (s, t, f) in A}

L = []
w = L.append
w('module\n')
MILD = spec.get('mild', False)
ZMOD = spec.get('zero_mod', False)
if MILD and ZMOD:
    w('public import LargeIndecomposable.Cleaving.Basic.ToolsMod\n')
else:
    w('public import LargeIndecomposable.Cleaving.Basic.Tools\n' if MILD else 'public import LargeIndecomposable.Cleaving.Basic.ThinDiagram\n')
w('/-!')
w(f'# The thin diagram `{N}`\n')
w(spec['doc'])
w('\nGenerated by `scripts/gen_thin_shape.py`.')
w('-/\n')
w('@[expose] public section\n')
w('set_option autoImplicit false\n')
w('noncomputable section\n')
w('namespace LargeIndecomposable\n')
w('open CategoryTheory Limits RayCat\n')
w('universe u\n')
w('namespace RayCat\n')
w(f'/-- Vertices of the diagram `{N}`. -/')
w(f'inductive {N}')
w('  | ' + ' | '.join(V))
w('  deriving DecidableEq\n')
w(f'namespace {N}\n')
w(f'instance : Fintype {N} := ⟨{{{", ".join(V)}}}, by intro v; cases v <;> simp⟩\n')
w('/-- The order (nonzero morphisms). -/')
w(f'def leb : {N} → {N} → Bool')
w('  | ' + ' | '.join(f'{x}, {y}' for (x, y) in sorted(le)) + ' => true')
w('  | _, _ => false\n')
w('/-- The arrows. -/')
w(f'def arb : {N} → {N} → Bool')
w('  | ' + ' | '.join(f'{s}, {t}' for (s, t) in sorted(ar)) + ' => true')
w('  | _, _ => false\n')
w('/-- The thin category. -/')
w(f'abbrev thin : ThinData {N} where')
w('  le x y := leb x y = true')
w('  nz x _ z := leb x z = true')
w('  refl x := by cases x <;> rfl')
w('  antisymm := by decide')
w('  nz_le _ _ _ _ _ h := h')
w('  nz_left _ _ h := h')
w('  nz_right _ _ h := h')
w('  assoc := by decide\n')
w('/-- The generating arrows. -/')
w(f'abbrev arrows : ThinArrows thin where')
w('  ar x y := arb x y = true')
w('  ar_le := by decide')
w('  ar_ne := by decide')
w('  first := by decide')
w('  last := by decide\n')
objargs = ' '.join(f'({o} := {o})' for o in O)
w('section Diagram\n')
w('variable {P : Type} [Category.{0} P] [HasZeroMorphisms P] {' + ' '.join(O) + ' : P}')
w('  ' + ' '.join(f'({f} : {obj[s]} ⟶ {obj[t]})' for (s, t, f) in A) + '\n')
w('/-- The objects. -/')
w(f'abbrev obj : {N} → P')
w('  ' + ' '.join(f'| {v} => {obj[v]}' for v in V) + '\n')
w('/-- The morphisms. -/')
w(f'abbrev tab : ∀ u v : {N}, (obj {objargs} u) ⟶ obj {objargs} v')
for (x, y) in sorted(le):
    w(f'  | {x}, {y} => {lval(chosen(x, y))}')
w('  | _, _ => 0\n')
w('end Diagram\n')
w(f'end {N}\n')
w('end RayCat\n')
if MILD:
    w('open RayQuiver\n')
    w('namespace RayCat\n')
    w('variable {P : Type} [Category.{0} P] [HasZeroMorphisms P] [IsRayCategory P] [Fintype P]')
    w('  [DecidableEq P] [IsFiniteRayCategory P] {k : Type*} [Field k] [Infinite k]\n')
else:
    w('namespace RayQuiver\n')
    w('namespace MulBasis\n')
    w('variable {P : Type} [Category.{0} P] [HasZeroMorphisms P] [IsRayCategory P] [Fintype P]')
    w('  [DecidableEq P] [IsFiniteRayCategory P] {k : Type u} [Field k] [Infinite k]')
    w('  {A : Type u} [Ring A] [Algebra k A] (B : MulBasis k P A)\n')

hyps = []
# commutativity: every path of every le pair equals the chosen one
comm = []
for (x, y) in sorted(le):
    c = chosen(x, y)
    for p in allp[(x, y)]:
        if p != c:
            comm.append((rval(p), rval(c)))
zr = []
zrp = []
for (x, y) in sorted(reach):
    if (x, y) in zero:
        for p in allp[(x, y)]:
            # only minimal zero paths: no proper subpath (x', y') in zero
            zr.append(rval(p))
            zrp.append((p, y))
for i, (l_, r_) in enumerate(comm):
    hyps.append((f'hc{i}', f'{l_} = {r_}'))
for i, z_ in enumerate(zr):
    if ZMOD:
        hyps.append((f'hz{i}', f'FactorsThroughMorphism τ ({z_})'))
    else:
        hyps.append((f'hz{i}', f'{z_} = 0'))
for (x, y) in sorted(le):
    if x != y:
        hyps.append((f'h0_{x}_{y}', f'¬FactorsThroughMorphism τ ({lval(chosen(x, y))})'))
for (s_, t_, f_) in A:
    hyps.append((f'hi_{f_}', f'¬IsIso {f_}'))
derived = []
for (x, z) in sorted(ar):
    for y in V:
        if (x, y) in le and not ((z, y) in le and (x, y) in le):
            if y == x:
                derived.append((f'hlft_{x}_{z}_{y}', f'¬∃ g, {arrmap[(x, z)]} ≫ g = 𝟙 _',
                                f'not_split_mono hi_{arrmap[(x, z)]}'))
            else:
                hyps.append((f'hlft_{x}_{z}_{y}',
                             f'¬∃ g, {arrmap[(x, z)]} ≫ g = {lval(chosen(x, y))}'))
for (z, y) in sorted(ar):
    for x in V:
        if (x, y) in le and not ((x, z) in le and (x, y) in le):
            if x == y:
                derived.append((f'hrgt_{x}_{z}_{y}', f'¬∃ g, g ≫ {arrmap[(z, y)]} = 𝟙 _',
                                f'not_split_epi hi_{arrmap[(z, y)]}'))
            else:
                hyps.append((f'hrgt_{x}_{z}_{y}',
                             f'¬∃ g, g ≫ {arrmap[(z, y)]} = {lval(chosen(x, y))}'))

mors = [f for (_, _, f) in A]
margs = ' '.join(mors)
w('set_option maxHeartbeats 16000000 in')
w(f'open {N} in')
if not MILD:
    w('include B in')
w(f'/-- **No cleaving diagram `{N}` in `P/τ`.** -/')
if MILD:
    w(f'theorem MildHyp.{spec["theorem"]} (hM : MildHyp k P) {{a b : P}} (τ : a ⟶ b) (hτ : ¬IsIso τ)')
else:
    w(f'theorem {spec["theorem"]}')
    w('    (hmin : ∀ I : TwoSidedIdeal A, I ≠ ⊥ → Statement.IsRepresentationFinite (A ⧸ I.asIdeal))')
    w('    (hL : LeftCancel P) (hR : RightCancel P) {a b : P} (τ : a ⟶ b) (hτ : ¬IsIso τ)')
w('    (hτ0 : τ ≠ 0) {' + ' '.join(O) + ' : P}')
w('    ' + ' '.join(f'({f} : {obj[s]} ⟶ {obj[t]})' for (s, t, f) in A))
w('    (hD : ¬Statement.IsRepresentationFinite (Linearization (ThinCat thin) k))')
for (n_, t_) in hyps:
    w(f'    ({n_} : {t_})')
w('    : False := by')
for (n_, t_, pf) in derived:
    w(f'  have {n_} : {t_} := {pf}')
rel = [n_ for (n_, _) in hyps if n_.startswith('hc') or (n_.startswith('hz') and not ZMOD)]
for n_ in rel:
    w(f"  have {n_}' := reassoc_of% {n_}")
simps = ', '.join([f"{n_}', {n_}" for n_ in rel])
zq = []
if ZMOD:
    for i, (p_, yv) in enumerate(zrp):
        mlist = list(p_)
        body = ' ≫ '.join(mlist + ['q'])
        w(f'  have hzq{i} : ∀ {{W : P}} (q : {obj[yv]} ⟶ W), FactorsThroughMorphism τ ({body}) :=')
        w(f'    fun q ↦ by simpa only [Category.assoc] using ftm_comp_right hz{i} q')
        zq.append(i)
if MILD and ZMOD:
    w(f'  refine hM.not_thin_diagram\' τ hτ hτ0 hD arrows obj (fun x y _ ↦ tab {margs} x y)')
elif MILD:
    w(f'  refine hM.not_thin_diagram τ hτ hτ0 hD arrows obj (fun x y _ ↦ tab {margs} x y)')
else:
    w(f'  refine B.not_thin_diagram hmin hL hR τ hτ hτ0 hD arrows obj (fun x y _ ↦ tab {margs} x y)')
w('    (fun x ↦ by cases x <;> rfl) ?_ ?_ ?_ ?_')
w('  · intro x y z h h\'')
w('    cases x <;> cases y <;> (try exact absurd h (by decide)) <;> cases z <;>')
w('      (try exact absurd h\' (by decide)) <;> split_ifs with hn <;>')
w('      (try exact absurd hn (by decide)) <;>')
if ZMOD:
    zt = ' | '.join([f'exact hz{i}' for i in zq] + [f'exact hzq{i} _' for i in zq] + ['apply ftm_comp_left'])
    w(f'      (try simp only [tab, Category.assoc, Category.id_comp, Category.comp_id, zero_comp, comp_zero{", " + simps if simps else ""}]) <;>')
    w(f'      (try (repeat (first | {zt})))')
else:
    w(f'      simp only [tab, Category.assoc, Category.id_comp, Category.comp_id, zero_comp, comp_zero{", " + simps if simps else ""}]')
w('  · intro x y h')
w('    cases x <;> cases y <;> first')
w('      | exact absurd h (by decide)')
w('      | exact not_factorsThrough_id hτ _')
w('      | assumption')
w('  · intro x z y ha hy')
w('    cases x <;> cases z <;> (try exact absurd ha (by decide)) <;> cases y <;>')
w('      (try exact absurd hy (by decide)) <;>')
w('      first')
w('      | exact fun _ ↦ by decide')
w('      | exact fun hg ↦ absurd hg ‹_›')
w('  · intro x z y ha hx')
w('    cases z <;> cases y <;> (try exact absurd ha (by decide)) <;> cases x <;>')
w('      (try exact absurd hx (by decide)) <;>')
w('      first')
w('      | exact fun _ ↦ by decide')
w('      | exact fun hg ↦ absurd hg ‹_›\n')
if MILD:
    w('end RayCat\n')
else:
    w('end MulBasis\n')
    w('end RayQuiver\n')
w('end LargeIndecomposable')
open(out, 'w').write('\n'.join(L) + '\n')
print(f'{len(hyps)} hypotheses:')
for (n_, t_) in hyps:
    print(f'  {n_} : {t_}')
